// Copies the built installers into website/downloads and writes website/release.js
// (version, file names, sizes, SHA-256) so the download page always matches the build.
// Run after `npm run app:build`:  npm run site:prepare
import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const conf = JSON.parse(readFileSync(join(root, "src-tauri", "tauri.conf.json"), "utf8"));
const version = conf.version;
const bundle = join(root, "src-tauri", "target", "release", "bundle");
const out = join(root, "website", "downloads");

const wanted = [
  { kind: "nsis", dir: "nsis", file: `Aktobly_${version}_x64-setup.exe`, label: "Installer (.exe)", recommended: true },
  { kind: "msi", dir: "msi", file: `Aktobly_${version}_x64_en-US.msi`, label: "MSI package (.msi)", recommended: false },
];

// Keep only the current release in the site folder.
if (existsSync(out)) for (const f of readdirSync(out)) rmSync(join(out, f));
mkdirSync(out, { recursive: true });

const files = wanted.map((w) => {
  const src = join(bundle, w.dir, w.file);
  if (!existsSync(src)) throw new Error(`Missing ${src}. Run "npm run app:build" first.`);
  copyFileSync(src, join(out, w.file));
  const buf = readFileSync(src);
  return {
    kind: w.kind,
    label: w.label,
    recommended: w.recommended,
    file: w.file,
    url: `downloads/${w.file}`,
    bytes: statSync(src).size,
    sha256: createHash("sha256").update(buf).digest("hex"),
  };
});

// Keep any hand-set fields (e.g. repoUrl) from the previous release.js.
const releasePath = join(root, "website", "release.js");
let previous = {};
if (existsSync(releasePath)) {
  const m = readFileSync(releasePath, "utf8").match(/=\s*(\{[\s\S]*\});?\s*$/);
  if (m) try { previous = JSON.parse(m[1]); } catch {}
}

const release = {
  repoUrl: previous.repoUrl ?? "",
  version,
  date: new Date().toISOString().slice(0, 10),
  files,
};
writeFileSync(
  releasePath,
  `// Generated by scripts/prepare-site.mjs. "repoUrl" is preserved between runs; set it to your public source repository.\nwindow.AKTOBLY_RELEASE = ${JSON.stringify(release, null, 2)};\n`,
);
for (const f of files) console.log(`${f.file}  ${(f.bytes / 1048576).toFixed(2)} MB  sha256 ${f.sha256}`);
console.log(`Wrote website/release.js (v${version})`);
